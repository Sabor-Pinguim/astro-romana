// Bundles the GLB files that index.html references into index.models.js (base64), so the
// prototype also works when opened straight from disk: browsers block fetch() on file://.
// The page looks for `rocket/...glb` and `parts/...glb` string literals; this script finds
// the same literals, so adding a model to the page and re-running is all it takes.
// Usage: npm run web:models
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '../..');
const modelsDir = path.join(root, 'godot/assets/models');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const files = [...new Set(html.match(/\b(?:rocket|parts)\/[\w/.-]+\.glb\b/g) ?? [])].sort();

let out = '// GENERATED by tools/web/bundle-models.mjs (npm run web:models). Do not edit.\n'
  + '// GLB models used by index.html, base64-encoded so the page works from file://.\n'
  + 'window.ASTRO_GLB = {\n';
let bytes = 0;
for (const file of files) {
  const data = fs.readFileSync(path.join(modelsDir, file));
  bytes += data.length;
  out += `  ${JSON.stringify(file)}: "${data.toString('base64')}",\n`;
}
out += '};\n';
fs.writeFileSync(path.join(root, 'index.models.js'), out);
console.log(`index.models.js: ${files.length} models, ${Math.round(bytes / 1024)} KB of GLB, ${Math.round(out.length / 1024)} KB written`);
for (const file of files) console.log(`  ${file}`);
